/**
 * Forza il download di un `Blob` come file lato browser.
 *
 * Crea un object URL temporaneo, simula il click su un `<a download>` e libera
 * l'URL subito dopo. Utile per gli scarichi binari (es. avviso PDF, ricevute).
 */
export function downloadBlob(blob: Blob, filename: string): void {
  const url = URL.createObjectURL(blob);
  const a = document.createElement('a');
  a.href = url;
  a.download = filename;
  a.style.display = 'none';
  document.body.appendChild(a);
  a.click();
  document.body.removeChild(a);
  // Revoca in un microtask successivo per non annullare il download in corso.
  setTimeout(() => URL.revokeObjectURL(url), 0);
}
